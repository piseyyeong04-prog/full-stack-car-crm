export function exportReportXls({ title, subtitle = '', columns, rows, filename = 'report' }) {
  const head = columns.map((c) => `<th>${esc(c.title)}</th>`).join('')
  const body = rows
    .map((r) => '<tr>' + columns.map((c) => `<td>${esc(r[c.key])}</td>`).join('') + '</tr>')
    .join('')
  const html = `<html xmlns:o="urn:schemas-microsoft-com:office:office" xmlns:x="urn:schemas-microsoft-com:office:excel" xmlns="http://www.w3.org/TR/REC-html40">
  <head><meta charset="utf-8">
  <!--[if gte mso 9]><xml><x:ExcelWorkbook><x:ExcelWorksheets><x:ExcelWorksheet>
  <x:Name>Report</x:Name><x:WorksheetOptions><x:DisplayGridlines/></x:WorksheetOptions>
  </x:ExcelWorksheet></x:ExcelWorksheets></x:ExcelWorkbook></xml><![endif]-->
  <style>
    table{border-collapse:collapse;font-family:Calibri,Arial,sans-serif;font-size:11pt}
    td,th{border:1px solid #b0b0b0;padding:5px 8px;vertical-align:middle}
    th{background:#0D76E1;color:#ffffff;font-weight:bold;text-align:left}
    .title{font-size:15pt;font-weight:bold;color:#0D76E1;border:none;padding-bottom:2px}
    .sub{font-size:9pt;color:#666666;border:none;padding-bottom:10px}
    .company{font-size:12pt;font-weight:bold;border:none}
    .even{background:#f2f6fb}
  </style></head>
  <body>
    <table>
      <tr><td class="company" colspan="${columns.length}">${esc(COMPANY.name)}</td></tr>
      <tr><td class="title" colspan="${columns.length}">${esc(title)}</td></tr>
      <tr><td class="sub" colspan="${columns.length}">${esc(subtitle)} · Generated ${esc(nowText())}</td></tr>
      <tr><td colspan="${columns.length}" style="border:none;height:6px"></td></tr>
      <tr>${head}</tr>
      ${body}
    </table>
  </body></html>`

  download(html, filename.endsWith('.xls') ? filename : filename + '.xls', 'application/vnd.ms-excel')
}
